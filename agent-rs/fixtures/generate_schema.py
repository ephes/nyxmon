"""Generate the Rust agent's schema contract from the Django migrations.

``agent-rs/PLAN.md`` section 2.4: Django migrations own the schema. This
script migrates a temporary database with the test settings and writes

* ``schema/schema.sql``: the DDL of every table and index (``sqlite_master``
  order) plus the ``django_migrations`` rows, from which every Rust store test
  builds its database;
* ``schema/agent_tables.json``: the columns of the four agent tables and the
  minimum nyxboard migration the Rust agent requires.

``tests/unit/test_agent_rs_schema_contract.py`` regenerates both in memory and
fails when they differ from the committed files, so a migration cannot merge
without a conscious update of the Rust contract (``nyxmon-store``'s
``schema.rs`` and PLAN.md section 2.2).

Usage::

    uv run python agent-rs/fixtures/generate_schema.py          # rewrite
    uv run python agent-rs/fixtures/generate_schema.py --check  # exit 1 on drift
"""

from __future__ import annotations

import argparse
import json
import os
import sqlite3
import subprocess
import sys
import tempfile
from collections.abc import Callable
from pathlib import Path

FIXTURES_DIR = Path(__file__).resolve().parent
SCHEMA_DIR = FIXTURES_DIR / "schema"
REPO_ROOT = FIXTURES_DIR.parent.parent
DJANGO_DIR = REPO_ROOT / "src" / "django"

#: The minimum migration level of the Rust agent (``MIN_NYXBOARD_MIGRATION``
#: in ``nyxmon-store``). Raising it is a breaking agent release (PLAN.md 2.4).
MIN_NYXBOARD_MIGRATION = ("nyxboard", "0013_site_connectivity_state")

AGENT_TABLES = (
    "health_check",
    "check_result",
    "check_notification_state",
    "collector_incident",
)

#: ``django_migrations.applied`` is wall-clock time; the fixture pins it.
APPLIED_AT = "2000-01-01 00:00:00"

_MIGRATE = """
import sys
import django
from django.conf import settings

settings.DATABASES["default"]["NAME"] = sys.argv[1]
django.setup()
from django.core.management import call_command

call_command("migrate", verbosity=0, interactive=False)
"""


def migrate(db_path: Path) -> None:
    """Run every Django migration on a new database at ``db_path``."""
    env = {
        **os.environ,
        "DJANGO_SETTINGS_MODULE": "config.settings.test",
        "PYTHONPATH": os.pathsep.join(
            [str(DJANGO_DIR), str(REPO_ROOT / "src"), os.environ.get("PYTHONPATH", "")]
        ),
    }
    subprocess.run(
        [sys.executable, "-c", _MIGRATE, str(db_path)],
        check=True,
        cwd=DJANGO_DIR,
        env=env,
    )


def _sql_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render_from_db(db_path: Path) -> dict[str, str]:
    """Render both contract files from a migrated database."""
    with sqlite3.connect(db_path) as connection:
        ddl = [
            row[0]
            for row in connection.execute(
                "SELECT sql FROM sqlite_master "
                "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid"
            )
        ]
        migrations = connection.execute(
            "SELECT app, name FROM django_migrations ORDER BY id"
        ).fetchall()
        tables = {
            table: [
                row[1]
                for row in connection.execute(f"PRAGMA table_info({table})").fetchall()
            ]
            for table in AGENT_TABLES
        }
    if tuple(MIN_NYXBOARD_MIGRATION) not in {tuple(row) for row in migrations}:
        raise RuntimeError(f"{MIN_NYXBOARD_MIGRATION} is not a Django migration")

    lines = [
        "-- The Django schema the Rust agent runs against (agent-rs/PLAN.md 2.4).",
        "-- Generated by agent-rs/fixtures/generate_schema.py from `manage.py migrate`;",
        "-- do not edit (`just rs-fixtures`).",
    ]
    lines.extend(f"{statement};" for statement in ddl)
    lines.extend(
        "INSERT INTO django_migrations (app, name, applied) VALUES "
        f"({_sql_literal(app)}, {_sql_literal(name)}, {_sql_literal(APPLIED_AT)});"
        for app, name in migrations
    )
    agent_tables = {
        "min_nyxboard_migration": list(MIN_NYXBOARD_MIGRATION),
        "tables": tables,
    }
    return {
        "schema.sql": "\n".join(lines) + "\n",
        "agent_tables.json": json.dumps(
            agent_tables, indent=1, sort_keys=True, ensure_ascii=True
        )
        + "\n",
    }


def render(prepare: Callable[[Path], None] | None = None) -> dict[str, str]:
    """Migrate a temporary database and render the contract files.

    Args:
        prepare: Optional hook run on the migrated database before rendering
            (the contract test simulates schema changes with it).
    """
    with tempfile.TemporaryDirectory() as directory:
        db_path = Path(directory) / "db.sqlite3"
        migrate(db_path)
        if prepare is not None:
            prepare(db_path)
        return render_from_db(db_path)


def stale_files(rendered: dict[str, str], directory: Path = SCHEMA_DIR) -> list[str]:
    """Return the contract files in ``directory`` that differ from ``rendered``."""
    stale = []
    for name, content in sorted(rendered.items()):
        path = directory / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(name)
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when a committed file is stale"
    )
    args = parser.parse_args(argv)
    rendered = render()
    if args.check:
        stale = stale_files(rendered)
        for name in stale:
            print(
                f"stale schema fixture: {name} (run `just rs-fixtures`)",
                file=sys.stderr,
            )
        return 1 if stale else 0
    SCHEMA_DIR.mkdir(exist_ok=True)
    for name, content in sorted(rendered.items()):
        (SCHEMA_DIR / name).write_text(content, encoding="utf-8")
        print(f"wrote {SCHEMA_DIR / name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
